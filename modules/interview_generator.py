"""Generate technical / HR / behavioral / scenario interview questions with the local LLM."""
from __future__ import annotations

import streamlit as st

import config
from ai.embeddings import EmbeddingError
from ai.generators import generate_questions
from ai.llm_engine import LLMError
from database.db import DatabaseError
from services import ensure_llm, get_db, get_rag
from utils import ui
from utils.validators import ValidationError, validate_int, validate_text

LEVELS = ["Intern / Entry", "Junior (0-2 yrs)", "Mid-level (3-5 yrs)", "Senior (6+ yrs)", "Lead / Manager"]
DIFFICULTIES = ["Easy", "Medium", "Hard"]
ICONS = {"Technical": "🛠️", "HR": "🤝", "Behavioral": "🧠", "Scenario": "🎯"}


def profile_selector(db, key: str) -> str:
    """Optional: personalise using the user's indexed documents (e.g. their CV). Returns context text."""
    docs = [d for d in db.list_documents() if d["status"] == "indexed"]
    if not docs:
        return ""
    use = st.checkbox("Personalise with my documents (e.g. CV)", key=f"{key}_use")
    if not use:
        return ""
    names = {d["id"]: d["name"] for d in docs}
    chosen = st.multiselect("Documents", list(names), default=list(names)[:1], format_func=names.get, key=f"{key}_docs")
    if not chosen:
        return ""
    try:
        return get_rag().sample_context(chosen, max_chars=1500, topic="skills experience projects education")
    except EmbeddingError as exc:
        st.warning(f"Could not read CV context; questions will be generated without personalisation. {exc}")
        return ""


def render() -> None:
    db = get_db()
    ui.page_header("Interview Question Generator", "Dynamic questions generated by your local LLM.")
    with st.form("gen_form"):
        c1, c2 = st.columns(2)
        job = c1.text_input("Job title", placeholder="e.g. Machine Learning Engineer")
        domain = c2.text_input("Technical domain", placeholder="e.g. NLP, backend, data engineering")
        c3, c4, c5 = st.columns(3)
        level = c3.selectbox("Experience level", LEVELS, index=2)
        difficulty = c4.selectbox("Difficulty", DIFFICULTIES, index=1)
        n = c5.number_input("Number of questions", 1, config.MAX_QUESTIONS, 8)
        submitted = st.form_submit_button("✨ Generate questions")
    profile = profile_selector(db, "gen")

    if submitted:
        try:
            job_v = validate_text(job, "Job title", 2, 100)
            domain_v = validate_text(domain, "Technical domain", 2, 100)
            n_v = validate_int(n, "Number of questions", 1, config.MAX_QUESTIONS)
        except ValidationError as exc:
            st.error(str(exc))
            return
        llm = ensure_llm()
        if llm is None:
            return
        try:
            with st.spinner("Generating questions… (CPU inference can take a minute)"):
                qs = generate_questions(llm, job_v, level, domain_v, n_v, difficulty, profile)
            sid = db.create_interview_session(job_v, level, domain_v, difficulty, qs, mode="generated", status="generated")
            st.session_state["gen_session_id"] = sid
            st.toast("Questions generated", icon="✨")
        except (LLMError, DatabaseError, EmbeddingError) as exc:
            st.error(str(exc))
            return

    sid = st.session_state.get("gen_session_id")
    sessions = db.list_interview_sessions(("generated",)) + [s for s in db.list_interview_sessions(("mock",))]
    if not sessions:
        ui.empty_state("Fill in the form above to generate your first question set.", "🧩")
        return
    ids = [s["id"] for s in sessions]
    sid = sid if sid in ids else ids[0]
    labels = {s["id"]: f"#{s['id']} · {s['job_title']} ({s['difficulty']}) · {s['created_at'][:16]}" for s in sessions}
    sid = st.selectbox("Question set", ids, index=ids.index(sid), format_func=labels.get)
    session = db.get_interview_session(sid)
    questions = db.get_interview_questions(sid)
    st.markdown(f"### {session['job_title']} · {session['experience_level']} · {session['domain']}")
    for cat in ["Technical", "Behavioral", "Scenario", "HR"]:
        group = [q for q in questions if q["category"] == cat]
        if group:
            st.markdown(f"#### {ICONS[cat]} {cat} questions")
            for i, q in enumerate(group, 1):
                st.markdown(f"{i}. {q['question']}")
    cols = st.columns([1, 1, 3])
    if session["status"] == "generated":
        def _start():
            db.update_interview_session(sid, mode="mock", status="in_progress")
            st.session_state["mock_session_id"] = sid
            ui.goto("🎤 Mock Interview")
        cols[0].button("🎤 Practise these", on_click=_start)
    if cols[1].button("🗑️ Delete set"):
        db.delete_interview_session(sid)
        st.session_state.pop("gen_session_id", None)
        st.rerun()
